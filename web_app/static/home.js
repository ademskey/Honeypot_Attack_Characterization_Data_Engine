window.addEventListener("DOMContentLoaded", () => {
    window.addEventListener("click", (e) => {
        if (!e.target.matches(".dropbtn")) {
            const dropdowns = document.getElementsByClassName("dropdown-content");
            for (let i = 0; i < dropdowns.length; i++) {
                dropdowns[i].classList.remove("show");
            }
        }
    });

    // When dropdown button for list of honeypots is selected
    function toggleDropdown() {
        document.getElementById("honeypot-dropdown").classList.toggle("show");
    }

    // When a honeypot is selected from the dropdown
    function selectHoneypot(name) {
        localStorage.setItem("selectedHoneypot", name);
    }

    // Attach dropdown functions to window
    window.toggleDropdown = toggleDropdown;
    window.selectHoneypot = selectHoneypot;

    // Status Text update:
    let isQuerying = false;
    let lastUpdated = null;  // server-provided timestamp

    const progressText = document.getElementById("progress-text");

    // Update display message based on status of query_and_process.main().
    // query_and_process.main() running: "Querying new data..."
    // Idling for an hour: incrementing timer shows elapsed time since last update
    function updateProgressText() {
        if (isQuerying) {
            progressText.textContent = "Querying new data...";
            return;
        }

        else if (lastUpdated) {
            const updatedDate = new Date(lastUpdated);
            const now = new Date();
            const elapsedMs = now - updatedDate;
            const elapsedSeconds = Math.floor(elapsedMs / 1000);
            const minutes = Math.floor(elapsedSeconds / 60);
            const seconds = elapsedSeconds % 60;
            progressText.textContent = `Time since last data pull: ${minutes}:${seconds.toString().padStart(2, '0')}`;
        }
        else {
            progressText.textContent = "Last update time not available.";
        }
    }

    // Check boolean flag generated by update_data_loop(). 
    function checkUpdateStatus() {
        fetch("/update_status", {
            headers: { 'X-Requested-By': 'frontend' }
        })
            .then(response => response.json())
            .then(data => {
                isQuerying = data.is_querying;
                lastUpdated = data.last_update_time;
            })
            .catch(err => {
                console.error("Status check failed:", err);
                isQuerying = false;
            });
    }

    // Check update_data_loop's status every 2 seconds
    setInterval(checkUpdateStatus, 2000);

    // Update web page every second
    setInterval(updateProgressText, 1000);
});
